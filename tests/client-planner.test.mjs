import test from "node:test";
import assert from "node:assert/strict";
import { setup } from "./client-fixture.mjs";
test("templates apply atomically, preserve explicit rules and become defaults only for new stars", async (t) => {
  const f = await setup(t, { movieRules: { 111: { paused: true } } });
  await f.client.api("template/save", { id: "evening", name: "我的晚场", rule: { timeFrom: "19:00", priority: "urgent" } });
  await f.client.api("template/default", { id: "evening" });
  await f.client.api("star", { id: "222", active: true });
  let prefs = await f.preferences();
  assert.equal(prefs.movieRules[222].timeFrom, "19:00");
  assert.equal(prefs.movieRules[111].paused, true);
  await f.client.api("template/apply", { id: "preset-imax", allStars: true, onlyUnset: true });
  prefs = await f.preferences();
  assert.equal(prefs.movieRules[222].priority, "urgent");
  await f.client.api("template/apply", { id: "preset-imax", movieIds: ["111"] });
  assert.deepEqual((await f.preferences()).movieRules[111].formats, ["IMAX"]);
  await f.client.api("template/delete", { id: "evening" });
  assert.equal((await f.preferences()).defaultRuleTemplateId, "");
  const writes = f.puts();
  await assert.rejects(f.client.api("template/apply", { id: "preset-imax", movieIds: ["111", "missing"] }));
  assert.equal(f.puts(), writes);
});
test("journal, bookings, notification preferences and notes stay encrypted and survive credential migration", async (t) => {
  const f = await setup(t);
  await f.client.api("journal/save", { id: "111", tags: ["私密标签"], review: "私密短评" });
  await f.client.api("journal/entry", { id: "111", entry: { id: "trip", type: "booked", startsAt: "2020-01-01T19:00:00+08:00", durationMinutes: 120, reminderMinutes: 30 }, stopMonitoring: true });
  await f.client.api("journal/entry-state", { id: "111", entryId: "trip", type: "watched" });
  await f.client.api("planner/settings", { quietEnabled: true, digestMinutes: 30 });
  let state = await f.client.load();
  assert.equal(state.filmJournal[111].entries.filter((e) => e.type === "watched").length, 1);
  assert.equal(state.movieRules[111].paused, true);
  assert.equal(state.notificationPrefs.digestMinutes, 30);
  assert.ok(!f.storage.get("polaris.public-cache.v1").includes("私密"));
  assert.ok(!f.storage.get("polaris.encrypted-cache.v1").includes("私密"));
  await f.client.rotateToken(f.nextToken, f.token);
  state = await f.client.load();
  assert.equal(state.filmJournal[111].review, "私密短评");
  assert.equal(state.notificationPrefs.quietEnabled, true);
  await f.client.api("journal/remove-entry", { id: "111", entryId: "trip" });
  assert.equal((await f.client.load()).filmJournal[111].entries.length, 0);
});
